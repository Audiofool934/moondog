#!/usr/bin/env node
// Builds src/integrations/score/vendor/dawn-sdk.mjs: the parts of the DAWN SDK (github.com/hraness/dawn-sdk,
// MIT) that Moondog uses to write a score, check it and render it to audio. The SDK ships TypeScript that
// Node cannot run as it is, so its sources are bundled here into one JavaScript module at a pinned commit.
// The bundle is checked in; run this only to move to another SDK version:
//
//   git clone https://github.com/hraness/dawn-sdk <folder> && git -C <folder> checkout <commit>
//   node scripts/vendor-dawn-sdk.mjs --sdk <folder> [--esbuild <path to the esbuild binary>]
//
// esbuild comes from the desktop app's own tools (app/node_modules) unless another one is given.
import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Moving to a newer SDK means changing these two lines and listening again: before its 1.0 a newer
// version may render the same score differently.
export const DAWN_SDK = Object.freeze({ version: "0.67.0", commit: "272ae807823c7dd8dd6fb750adb988616c8a6149" });

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "src", "integrations", "score", "vendor", "dawn-sdk.mjs");

// Only what Moondog calls. Song source is never evaluated here, so the SDK's sandbox (QuickJS) stays out.
const entry = (sdk) => [
  `export { ambientVoicing, ambientVoicingNames, chord, hit, note, progression, song, track, SONG_CALIBRATION_LATEST, DawnSdkError } from ${JSON.stringify(path.join(sdk, "core/sdk/v1.ts"))};`,
  `export { scoreFromJSON, ScoreValidationError } from ${JSON.stringify(path.join(sdk, "core/score.ts"))};`,
  `export { renderArrangedPcm } from ${JSON.stringify(path.join(sdk, "src/audio/arrange.ts"))};`,
  `export { exportSampleRate } from ${JSON.stringify(path.join(sdk, "src/audio/measure.ts"))};`,
  `export { lintSong } from ${JSON.stringify(path.join(sdk, "core/lint/index.ts"))};`,
  "",
].join("\n");

function option(name) {
  const at = process.argv.indexOf(name);
  return at === -1 ? null : process.argv[at + 1] ?? null;
}

const fail = (message) => {
  console.error(message);
  process.exit(1);
};

async function main() {
  const sdk = option("--sdk") ? path.resolve(option("--sdk")) : null;
  if (!sdk) fail("usage: node scripts/vendor-dawn-sdk.mjs --sdk <checkout of hraness/dawn-sdk> [--esbuild <binary>]");
  const esbuild = path.resolve(option("--esbuild") ?? path.join(root, "app", "node_modules", ".bin", "esbuild"));
  if (!(await stat(esbuild).catch(() => null))) fail(`esbuild is not at ${esbuild}. Run npm ci in app/, or pass --esbuild.`);

  const git = (...args) => spawnSync("git", ["-C", sdk, ...args], { encoding: "utf8" });
  const head = git("rev-parse", "HEAD").stdout.trim();
  if (head !== DAWN_SDK.commit) fail(`The checkout is at ${head || "no commit"}, not the pinned ${DAWN_SDK.commit}.`);
  if (git("diff", "--quiet", "HEAD").status !== 0) fail("The checkout has changed files. Vendor only an unmodified checkout.");
  const version = JSON.parse(await readFile(path.join(sdk, "package.json"), "utf8")).version;
  if (version !== DAWN_SDK.version) fail(`The checkout is version ${version}, not the pinned ${DAWN_SDK.version}.`);

  const work = await mkdtemp(path.join(os.tmpdir(), "moondog-dawn-sdk-"));
  try {
    const entryFile = path.join(work, "entry.ts");
    const built = path.join(work, "dawn-sdk.mjs");
    await writeFile(entryFile, entry(sdk), "utf8");
    // Whitespace and syntax are shortened; names stay, so a stack trace still reads against the SDK's source.
    const run = spawnSync(esbuild, [entryFile, "--bundle", "--format=esm", "--platform=node", "--target=node22",
      "--minify-whitespace", "--minify-syntax", "--legal-comments=none", `--outfile=${built}`, "--log-level=warning"], { encoding: "utf8" });
    if (run.status !== 0) fail(`esbuild failed:\n${run.stderr}`);
    const code = await readFile(built, "utf8");
    const banner = [
      "// Generated by scripts/vendor-dawn-sdk.mjs. Do not edit: change the script's pin and run it again.",
      `// DAWN SDK ${DAWN_SDK.version} (github.com/hraness/dawn-sdk at ${DAWN_SDK.commit}), MIT License,`,
      "// Copyright (c) 2026 XTE Industries LLC. The license text is in licenses/dawn-sdk-mit.md.",
      "// Bundled: the score SDK, the score model, the offline renderer, the loudness helper and the lint.",
      `export const DAWN_SDK = Object.freeze(${JSON.stringify(DAWN_SDK)});`,
      "",
    ].join("\n");
    await mkdir(path.dirname(output), { recursive: true });
    await writeFile(output, banner + code, "utf8");
    console.log(`wrote ${path.relative(root, output)} · ${Math.round((banner.length + code.length) / 1024)} KB · DAWN SDK ${DAWN_SDK.version}`);
  } finally {
    await rm(work, { recursive: true, force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
